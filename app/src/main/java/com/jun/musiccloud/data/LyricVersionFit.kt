package com.jun.musiccloud.data

/**
 * 6.6：歌词「版本拟合」——**已彻底停用**。
 *
 * 背景：这个文件以前会根据「歌词末行落在歌曲时长的百分比」猜一个缩放系数，
 * 把整条时间轴按比例压缩/拉伸，试图把错版歌词硬掰回音源长度。结果是：
 *   · durationMs 在在线歌曲上经常先返回 0 / 试听时长 / 上一首残留值，拿它当分母
 *     就会把整条轴压缩，听感是「开头还行，越唱歌词越往前跑」；
 *   · 一旦压缩/拉伸，逐句误差随播放**线性累积**，用户拿「歌词时间校准」（只能整体
 *     平移）永远调不回来，表现就是「歌词自己在加速 / 突然跳一大段」。
 *
 * 主流播放器（酷狗 / 酷我 / QQ 音乐 / 网易云）都不改歌词时间轴：它们保证平台返回的
 * 歌词和自己播放的音源是**同一个版本**。版本不同就换源 / 换歌词，绝不靠客户端偷改。
 * 本项目现在也走这条路——版本一致性在数据层用「版本指纹」解决（见
 * OnlineMusicApi.resolveNeteaseIdBlocking），匹配不上直接显示「未找到匹配歌词」，
 * 不拿近似结果硬套。
 *
 * 保留这个类与 [fit] 签名，是为了不改动 LyricParser 等历史调用点；
 * 函数体恒为原样返回。时间校准只保留 `[offset:]` 与用户手动校准的**整体平移**
 * （LyricTimeFit.applyOffset）——平移不改变演唱速率，不会累积漂移。
 */
object LyricVersionFit {

    /**
     * 恒等返回：不再对时间轴做任何缩放 / 首尾重映射。
     *
     * 请到 OnlineMusicApi 用版本指纹保证音源与歌词同源；本函数只作历史兼容占位。
     */
    fun fit(lines: List<LyricLine>, durationMs: Long): List<LyricLine> = lines
}
